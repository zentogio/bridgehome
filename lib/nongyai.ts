const RED_RE =
  /(เจ็บหน้าอก|แน่นหน้าอก|หายใจไม่ออก|หายใจไม่อิ่ม|หายใจลำบาก|หมดสติ|เป็นลม|ล้มลง|ล้ม(?!เหลว)|ชัก|พูดไม่ชัด|แขนขาอ่อนแรง|อยากตาย|ไม่อยากอยู่|ทำร้ายตัวเอง|ฆ่าตัวตาย)/;

export function detectRed(text: string): string | null {
  const m = text.match(RED_RE);
  return m ? m[1] : null;
}

