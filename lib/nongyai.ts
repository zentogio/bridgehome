const NEG_FIX = /(ไม่เหนื่อย|ไม่เศร้า|ไม่เหงา|ไม่เครียด|ไม่ท้อ|หลับสบาย|หลับดี|กินแล้ว|ทานแล้ว|กินครบ|สบายดี|ดีค่ะ|ดีจ้ะ|ดีจ้า)/;

export function judge(step: Step, text: string): boolean {
  // คืนค่า true = ดี/ปกติ (ยกเว้น q2 ที่ true = ตอบ "มี")
  if (step === "q2a" || step === "q2b") {
    if (/(ไม่มี|ไม่เป็น|ไม่ค่ะ|ไม่จ้ะ|ไม่เลย|ปกติ)/.test(text)) return false;
    return /(มี|ใช่|บ้าง|เป็น|เศร้า|เบื่อ|ท้อ|หดหู่)/.test(text);
  }
  if (NEG_FIX.test(text) && !BAD[step]?.test(text.replace(NEG_FIX, ""))) return true;
  return !BAD[step]?.test(text);
}

export function nextStep(step: Step): Step {
  return ORDER[ORDER.indexOf(step) + 1] ?? "done";
}

