export function closing(a: Answers): { level: Level; text: string; summary: string } {
  const bad: string[] = [];
  if (a.sleep === false) bad.push("นอนไม่ค่อยหลับ");
  if (a.meds === false) bad.push("ยังไม่ได้กินยา");
  if (a.food === false) bad.push("กินข้าวได้น้อย");
  if (a.mood === false) bad.push("อารมณ์ไม่ดี");
  const q2pos = a.q2a || a.q2b;
  if (a.red) {
    return {
      level: "red",
      text: RED_REPLY,
      summary: `พูดถึง “${a.red}” → แจ้งเตือนสีแดงตามกฎตายตัว`,
    };
  }
  if (q2pos) {
    return {
      level: "yellow",
      text: "ขอบคุณที่เล่าให้น้องใยฟังนะคะ น้องใยจะบอกคุณเพ็ญให้โทรมาคุยด้วยค่ะ พรุ่งนี้น้องใยขอถามเพิ่มอีกนิดนะคะ",
      summary: `ตอบ “มี” ในข้อคัดกรอง 2Q → แนะนำประเมิน 9Q พรุ่งนี้${bad.length ? " · " + bad.join(", ") : ""}`,
    };
  }
  if (bad.length >= 2) {
    return {
      level: "yellow",
      text: "น้องใยบอกคุณเพ็ญให้แล้วนะคะ ดูแลตัวเองดีๆ แล้วเจอกันพรุ่งนี้เช้านะคะ",
      summary: bad.join(", "),
    };
  }
  return {
    level: "green",
    text: "เยี่ยมเลยค่ะ น้องใยจะส่งข่าวดีให้คุณเพ็ญนะคะ พรุ่งนี้เช้าเจอกันใหม่ค่ะ",
    summary: bad.length ? bad.join(", ") : "นอนหลับดี กินยาครบ กินข้าวได้ อารมณ์ปกติ",
  };
}

